"""Render a PNG preview of every look and write catalog.md (+ catalog.png contact sheet).

    python -m mvkit.catalog --audio song.wav --project "Song.reborn" [--footage-dir footage-cache --clip eruption]

Previews are rendered against a real song so the audio-reactive parts show. Each look is shown at a moment
that suits it (a drop hit for drop looks, a calm moment for intros). Layer looks are drawn over black.
"""
import json, os, argparse, tempfile
from PIL import Image, ImageDraw
from .engine import Storyboard, Renderer, load_library, HERE

# when in the song to sample each kind of look (section-relative so it works for any RE:BORN song with these names)
WHEN = {'drop': ['Drop 1+1.02beats', 'Drop 2+1.02beats', 'Drop+1.02beats'], 'intro': ['Intro+6s', 'Intro'],
        'build': ['Build 1+3bars', 'Build 2+3bars'], 'switch': ['Fast switch+2.05beats'], 'bridge': ['Psych bridge+2bars']}
AT = {'star-sparkle': 'Intro+9.02s', 'strobe-deck': 'Fast switch+0.05beats'}   # per-look override
PRESET = {  # params that make a representative still
    'julia-drift': {'cAngle': 2.33, 'zoom': 1.45, 'hue': 0.6},
    'neon-kaleido': {'spin': 0.4, 'hue': 0.2},
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--audio', required=True); ap.add_argument('--project', required=True)
    ap.add_argument('--footage-dir', default=os.path.join(HERE, 'footage-cache')); ap.add_argument('--clip', default='eruption')
    ap.add_argument('--size', default='640x360')
    a = ap.parse_args()
    W, H = map(int, a.size.split('x'))
    lib = load_library()
    out_dir = os.path.join(HERE, 'previews'); os.makedirs(out_dir, exist_ok=True)
    rows = []
    for name, lk in lib.items():
        fits = lk.get('fits', '')
        layer = fits.startswith('layer')
        kind = next((k for k in ('drop', 'switch', 'bridge', 'build', 'intro') if k in fits), 'drop')
        if layer:
            kind = 'drop'
        scene = {'from': 0, 'look': 'shock-ring' if layer else name, 'params': PRESET.get(name, {}),
                 'travel': {'base': 0.6, 'kick': 2.0, 'snare': 1.2, 'bass': 0.6}, 'cutOn': ['kick', 'snare'],
                 'post': {'bloom': 0.5, 'grain': 0.03}}
        if layer:
            scene.update(params={'color': [0, 0, 0]}, layers=[{'look': name, 'amount': 2.0 if name == 'star-sparkle' else 1.0}])
        if name.startswith('footage'):
            scene['clips'] = [a.clip]; scene['clipStart'] = 6.0
        sb = {'audio': os.path.abspath(a.audio), 'project': os.path.abspath(a.project), 'footageDir': os.path.abspath(a.footage_dir),
              'scenes': [scene], 'impact': {'flash': 0, 'ca': 0, 'shake': 0}}
        tmp = tempfile.NamedTemporaryFile('w', suffix='.json', delete=False); json.dump(sb, tmp); tmp.close()
        st = Storyboard(tmp.name, W, H)
        t = None
        for spec in ([AT[name]] if name in AT else []) + WHEN[kind]:
            try:
                t = st.T(spec); break
            except ValueError:
                pass
        t = 27.0 if t is None else t
        r = Renderer(st, W, H)
        p = os.path.join(out_dir, f'{name}.png')
        r.still(t, p, warm=12)
        os.unlink(tmp.name)
        print('preview', name, f'@{t:.2f}s', flush=True)
        rows.append((name, lk))
    # catalog.md
    md = ['# Look catalog', '', 'Generated by `python -m mvkit.catalog`. Every look is a GLSL file in `looks/`; '
          'use it in a storyboard scene as `"look": "<name>"` (or as a layer). Parameters can be numbers, `[r,g,b]` lists, '
          'or expression strings evaluated every frame (see README).', '']
    for name, lk in rows:
        md += [f'## {lk.get("title", name)} — `{name}`', '', f'![{name}](previews/{name}.png)', '',
               f'**Fits:** {lk.get("fits", "")}  ·  **Mood:** {lk.get("mood", "")}', '', lk.get('desc', ''), '',
               '| param | default | what it does |', '|---|---|---|']
        md += [f'| `{p}` | {",".join(f"{v:g}" for v in d["default"])} | {d["desc"]} |' for p, d in lk['params'].items() if p != 'off']
        md.append('')
    open(os.path.join(HERE, 'catalog.md'), 'w').write('\n'.join(md))
    # contact sheet
    cols = 4; tw, th = 480, 270; rowsn = (len(rows) + cols - 1) // cols
    sheet = Image.new('RGB', (tw * cols, (th + 28) * rowsn), (12, 12, 14))
    d = ImageDraw.Draw(sheet)
    for i, (name, lk) in enumerate(rows):
        im = Image.open(os.path.join(out_dir, f'{name}.png')).convert('RGB').resize((tw, th))
        x, y = (i % cols) * tw, (i // cols) * (th + 28)
        sheet.paste(im, (x, y)); d.text((x + 8, y + th + 8), f'{name}  ·  {lk.get("fits", "")[:40]}', fill=(230, 230, 230))
    sheet.save(os.path.join(HERE, 'catalog.png'))
    print('wrote catalog.md, catalog.png')


if __name__ == '__main__':
    main()
